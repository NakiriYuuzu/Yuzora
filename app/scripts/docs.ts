import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

export type Command = { name: string; about: string; args: { name: string; required: boolean }[] };
export type Reference = { help: string; commands: Command[] };

const cell = (value: string) => value.replaceAll("|", "\\|").replaceAll("\n", " ");
const code = (value: string) => `\`${cell(value)}\``;
const banner = "<!-- Generated by scripts/docs.ts. Run just docs-generate; do not edit. -->\n";

export function commandPage(commands: Command[]): string {
  return `${banner}\n# Commands\n\nInspect the window with \`herdr-app ls\` and \`herdr-app status\`.\n\`herdr-app commands\` lists the app actions below, even without an open window.\n\nRun an action in the open window with \`herdr-app do\`:\n\n\`\`\`sh\nherdr-app do pane.split --direction right\nherdr-app do pane.split '{"direction":"right"}'\n\`\`\`\n\nArguments can be named flags or one JSON object. Required arguments are marked below.\nActions use the current selection unless you give an explicit target.\nSome actions close terminals; read their descriptions before running them.\nMods can add their own actions, which are not listed here.\n\n${commands.map(c => `## ${code(c.name)}\n\n${c.about}\n\n${c.args.length ? "| Argument | Required |\n|---|---|\n" + c.args.map(a => `| ${code(a.name)} | ${a.required ? "yes" : "no"} |`).join("\n") : "No arguments."}`).join("\n\n")}\n\n[Back to Herdr](../README.md)\n`;
}

// Split shell examples without running them. Quotes group arguments, not flags.
function shellCommands(source: string): string[][] {
  const commands: string[][] = [[]];
  let word = "", started = false, quote = "";
  const flush = () => {
    if (started) commands.at(-1)!.push(word);
    word = "";
    started = false;
  };
  for (let i = 0; i < source.length; i++) {
    const c = source[i];
    if (c === "\\" && quote !== "'" && i + 1 < source.length) {
      const next = source[i + 1];
      if (!quote || /["\\$`\n]/.test(next)) { word += next === "\n" ? "" : next; i++; started = true; continue; }
    }
    if (quote) {
      if (c === quote) quote = "";
      else word += c;
    } else if (c === "'" || c === '"') {
      quote = c;
      started = true;
    } else if (c === "#" && !started) {
      break;
    } else if (/[;&|\n]/.test(c)) {
      flush();
      if (commands.at(-1)!.length) commands.push([]);
    } else if (/\s/.test(c)) flush();
    else { word += c; started = true; }
  }
  flush();
  return commands;
}

export function checkExample(source: string, ref: Reference): string[] {
  const errors: string[] = [];
  const verbs = new Set([...ref.help.matchAll(/^\s+herdr-app\s+([\w-]+)/gm)].map(m => m[1]));
  verbs.add("--help"); // The help used to build this reference was obtained with this flag.
  for (const words of shellCommands(source)) {
    const start = words.findIndex(w => /^(?:\.\/|[\w./-]+\/)?herdr-app(?:\.exe)?$/.test(w));
    if (start < 0) continue;
    const args = words.slice(start + 1);
    const verb = args.shift();
    if (!verb) continue;
    if (!verbs.has(verb)) { errors.push(`unknown command or flag: ${verb}`); continue; }
    if (verb !== "do") {
      for (const arg of args) if (arg.startsWith("-")) errors.push(`unknown flag for ${verb}: ${arg}`);
      continue;
    }
    const name = args.shift();
    if (!name || name.startsWith("<")) continue;
    const command = ref.commands.find(c => c.name === name);
    if (!command) { errors.push(`unknown app command: ${name}`); continue; }
    if (args.length === 1 && args[0].trimStart().startsWith("{")) continue;
    const flags = new Set(command.args.map(a => `--${a.name}`));
    for (let i = 0; i < args.length; i += 2) {
      const flag = args[i];
      if (!flags.has(flag)) errors.push(`unknown flag for do: ${flag}`);
      if (i + 1 === args.length) errors.push(`missing value for ${flag}`);
    }
  }
  return errors;
}

export function checkMarkdown(file: string, source: string, ref: Reference): string[] {
  const errors: string[] = [];
  const lines = source.split("\n");
  let fence: string | undefined;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const marker = line.trim().match(/^(`{3,}|~{3,})/);
    if (marker) {
      if (!fence) fence = marker[1];
      else if (marker[1][0] === fence[0] && marker[1].length >= fence.length) fence = undefined;
      continue;
    }
    const snippets = fence ? [line] : [...line.matchAll(/`([^`]+)`/g)].map(m => m[1]);
    for (let snippet of snippets) {
      const at = i + 1;
      while (fence && snippet.endsWith("\\") && i + 1 < lines.length) {
        snippet = snippet.slice(0, -1) + " " + lines[++i].trim();
      }
      errors.push(...checkExample(snippet, ref).map(e => `${file}:${at}: ${e}`));
    }
  }
  return errors;
}

async function run(binary: string, arg: string): Promise<string> {
  const result = Bun.spawnSync([resolve(binary), arg], { env: { ...process.env, HERDR_APP_HOME: resolve("target/docs-no-window") } });
  if (result.exitCode !== 0) throw new Error(`${binary} ${arg}: ${result.stderr.toString()}`);
  return result.stdout.toString();
}

async function main() {
  const [mode, binary = `target/debug/herdr-app${process.platform === "win32" ? ".exe" : ""}`] = process.argv.slice(2);
  if (mode !== "generate" && mode !== "check") throw new Error("usage: bun scripts/docs.ts <generate|check> [binary]");
  const ref = { help: await run(binary, "--help"), commands: JSON.parse(await run(binary, "commands")) as Command[] };
  const pages = { "docs/commands.md": commandPage(ref.commands) };
  const errors: string[] = [];
  for (const [file, content] of Object.entries(pages)) {
    if (mode === "generate") await writeFile(file, content);
    else if (await readFile(file, "utf8").catch(() => "") !== content) errors.push(`${file}:1: stale generated page; run just docs-generate`);
  }
  const files = ["README.md", ...(await readdir("docs")).filter(f => f.endsWith(".md")).sort().map(f => `docs/${f}`)];
  for (const file of files) errors.push(...checkMarkdown(file, await readFile(file, "utf8"), ref));
  if (errors.length) throw new Error(errors.join("\n"));
  console.log(`${mode === "generate" ? "Generated references and checked" : "Checked references and"} CLI examples in ${files.length} pages.`);
}

if (import.meta.main) await main();
