//! Yuzora's one place in the herdr-app shell (yuzora: everything Yuzora adds
//! to the upstream app is here or in crates/yuzora-*, defaults/mods/yuzora-*,
//! defaults/layouts/yuzora.json, defaults/themes/yuzora-*.json and
//! defaults/yuzora/). Upstream files only call in, at lines marked `yuzora:`.
//!
//! - Branding: name, ids, links ([`APP_NAME`], [`BUNDLE_ID`], …).
//! - What Yuzora turns off: telemetry, feedback to herdr.dev, app self-update,
//!   update-notes media from media.herdr.dev.
//! - [`with_modules`]: every `yuzora:*` HostModule, for each mod copy.
//! - The default layout and the core layout document Yuzora uses.

use gpui_shell::policy::Policy;
use std::path::{Path, PathBuf};

pub mod shell;

/// The name people see (window title, setup screen).
pub const APP_NAME: &str = "Yuzora";
/// macOS bundle id, also the Linux/Wayland app id and Windows AppUserModelID.
pub const BUNDLE_ID: &str = "dev.yuuzu.yuzora";
/// What a fresh install shows (`layouts/yuzora.json`).
pub const DEFAULT_LAYOUT: &str = "yuzora";
/// Yuzora's layout document in herdr-core (`doc.get {name}`): its own, so
/// Yuzora and the official Herdr app never overwrite each other's spaces and
/// tabs. See docs/beta2/architecture.md, "herdr-core layout document".
pub const CORE_DOCUMENT: &str = "yuzora";
pub const ISSUES_URL: &str = "https://github.com/NakiriYuuzu/Yuzora/issues/new";
pub const RELEASES_URL: &str = "https://github.com/NakiriYuuzu/Yuzora/releases";
/// Nothing is collected and nothing is sent, whatever settings or env say.
pub const TELEMETRY_OFF: bool = true;
/// The app never updates itself from herdr.dev (L7 brings GitHub Releases).
/// herdr-core's own update channel stays as Herdr ships it.
pub const APP_SELF_UPDATE_OFF: bool = true;
/// Herdr's update notes (CHANGELOG.md) link pictures on media.herdr.dev; the
/// app never downloads them.
pub const UPDATE_NOTES_MEDIA_OFF: bool = true;

/// The app home (`~/.config/yuzora`, `$YUZORA_APP_HOME`); never Herdr's.
pub fn app_home() -> PathBuf {
    yuzora_core::paths::app_home()
}

fn init_once() {
    static ONCE: std::sync::Once = std::sync::Once::new();
    ONCE.call_once(|| {
        // Asked on every call: this runs before the setup screen installs or picks a core.
        yuzora_core::remote::set_hc_program(crate::core_bin::path);
        yuzora_core::js::set_refresh_hook(|| crate::mods::request(crate::mods::Request::Refresh));
    });
}

/// Every Yuzora module: `yuzora:core` (for this mod's strings) and one per lane.
pub fn host_modules(mod_name: &str) -> Vec<gpui_shell::HostModule> {
    vec![
        yuzora_core::host_module_for(mod_name),
        yuzora_shell::host_module(),
        yuzora_git::host_module(),
        yuzora_db::host_module(),
        yuzora_ssh::host_module(),
        yuzora_files::host_module(),
        yuzora_settings::host_module(),
        yuzora_perf::host_module(),
    ]
}

/// Adds every `yuzora:*` module to a mod's policy. `mod_name`: the mod copy's
/// folder name (`""` for `herdr-app check`).
pub fn with_modules(policy: Policy, mod_name: &str) -> Policy {
    init_once();
    host_modules(mod_name)
        .into_iter()
        .fold(policy, |p, m| p.with_host_module(m).expect("yuzora modules are valid"))
}

/// `yuzora.d.ts` in the app home, beside `herdr.d.ts`: what agents writing a
/// Yuzora mod import.
pub fn write_workspace(home: &Path) -> std::io::Result<()> {
    let path = home.join("yuzora.d.ts");
    let text = declarations();
    if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(path, text)?;
    }
    Ok(())
}

fn declarations() -> String {
    let mut out = String::from("// Yuzora's modules (generated by the app on every start; don't edit).\n");
    for m in host_modules("") {
        out.push_str(&format!("\ndeclare module \"{}\" {{{}}}\n", m.name(), m.declared().unwrap_or_default()));
    }
    out
}

/// Feedback goes to Yuzora's GitHub issues, never to herdr.dev. Returns
/// whether it was handled (always: the caller stops there).
pub fn open_feedback(message: Option<String>, cx: &mut gpui::App) -> bool {
    cx.open_url(&issue_url(message.as_deref()));
    true
}

fn issue_url(message: Option<&str>) -> String {
    let body = message.map(str::trim).filter(|m| !m.is_empty());
    let version = env!("CARGO_PKG_VERSION");
    let os = format!("{} {}", std::env::consts::OS, std::env::consts::ARCH);
    let text = format!("{}\n\n---\nYuzora {version} · {os}", body.unwrap_or(""));
    format!("{ISSUES_URL}?body={}", encode(text.trim_start()))
}

/// Percent-encodes everything but unreserved characters (RFC 3986).
fn encode(s: &str) -> String {
    s.bytes()
        .map(|b| match b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'.' | b'_' | b'~' => (b as char).to_string(),
            _ => format!("%{b:02X}"),
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_yuzora_module_validates_with_a_unique_name() {
        let modules = host_modules("yuzora-modebar");
        let mut names: Vec<&str> = modules.iter().map(|m| m.name()).collect();
        for m in &modules {
            m.validate().unwrap_or_else(|e| panic!("{}: {}", m.name(), e.message()));
            assert!(m.name().starts_with("yuzora:"));
        }
        names.sort();
        names.dedup();
        assert_eq!(names.len(), 8);
        let d = declarations();
        assert!(d.contains("declare module \"yuzora:core\"") && d.contains("declare module \"yuzora:git\""));
    }

    #[test]
    fn nothing_goes_to_herdr_dev() {
        assert!(TELEMETRY_OFF && APP_SELF_UPDATE_OFF && UPDATE_NOTES_MEDIA_OFF);
        assert!(!crate::feedback::available(), "feedback must have no endpoint");
        crate::telemetry::set_setting(true);
        assert!(!crate::telemetry::collecting(), "telemetry must stay off even when settings ask for it");
        assert_eq!(crate::update::status()["app"]["updates"], false);
        let url = issue_url(Some("broken & slow"));
        assert!(url.starts_with("https://github.com/NakiriYuuzu/Yuzora/issues/new?body=broken%20%26%20slow"));
        assert!(!url.contains("herdr.dev"));
    }

    #[test]
    fn the_yuzora_layout_and_theme_ship() {
        assert!(crate::window::shipped_layouts().contains(&DEFAULT_LAYOUT));
        assert!(crate::settings::SHIPPED_THEMES.contains(&"yuzora-dark"));
    }
}
